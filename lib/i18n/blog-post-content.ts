export function getLocalizedBlogPost(
  locale: Locale,
  post: BlogPost,
): BlogPost {
  const card = getBlogIndexContent(locale).articles.find(
    (a) => a.href === `/blog/${post.slug}` || a.href.endsWith(`/${post.slug}`),
  );

  const heContent = locale === "he" ? HE_CONTENT[post.slug] : undefined;

  if (!card && !heContent) return post;

  return {
    ...post,
    category: card?.category ?? post.category,
    title: card?.title ?? post.title,
    thesis: card?.thesis ?? post.thesis,
    readTime: card?.readTime ?? post.readTime,
    tags: card?.tags ?? post.tags,
    content: heContent ?? post.content,
  };
}
